export function t(key: string, lang: Lang = 'tr', params?: Record<string, string | number>): string {
  let text = translations[lang]?.[key] || translations.en?.[key] || translations.tr[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}

/** Prefer language-specific copy; fall back to English then Turkish. */
export function pickLang(
  lang: Lang,
  map: { tr: string; en: string; ar?: string; fil?: string },
): string {
  if (lang === 'tr') return map.tr;
  if (lang === 'ar') return map.ar ?? map.en;
  if (lang === 'fil') return map.fil ?? map.en;
  return map.en;
}

export function localeForLang(lang: Lang): string {
  if (lang === 'tr') return 'tr-TR';
  if (lang === 'ar') return 'ar';
  if (lang === 'fil') return 'fil-PH';
  return 'en-US';
}
